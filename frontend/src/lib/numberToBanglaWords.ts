function twoDigitsToBangla(n: number): string {
  if (n === 0) return '';
  if (n < 20) return ONES[n];
  if (SPECIALS[n]) return SPECIALS[n];
  const ten = Math.floor(n / 10);
  const one = n % 10;
  return TENS[ten] + (one > 0 ? ' ' + ONES[one] : '');
}

export function numberToBanglaWords(num: number): string {
  if (num === 0) return 'শূন্য টাকা মাত্র';
  let n = Math.floor(Math.abs(num));
  let result = '';

  const crore = Math.floor(n / 10000000);
  n %= 10000000;

  const lakh = Math.floor(n / 100000);
  n %= 100000;

  const thousand = Math.floor(n / 1000);
  n %= 1000;

  const hundred = Math.floor(n / 100);
  n %= 100;

  if (crore > 0) {
    result += numberToBanglaWords(crore).replace(' টাকা মাত্র', '') + ' কোটি ';
  }
  if (lakh > 0) {
    result += twoDigitsToBangla(lakh) + ' লাখ ';
  }
  if (thousand > 0) {
    result += twoDigitsToBangla(thousand) + ' হাজার ';
  }
  if (hundred > 0) {
    result += ONES[hundred] + ' শত ';
  }
  if (n > 0) {
    result += twoDigitsToBangla(n) + ' ';
  }

  return result.trim() + ' টাকা মাত্র';
}

export function toBanglaDigit(num: number | string): string {
  const banglaDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (w) => banglaDigits[+w]);
}
